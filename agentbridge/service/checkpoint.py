"""Checkpoints and rollback: git, run where git cannot hurt anyone (I-3).

A git repository is a program. ``core.fsmonitor``, ``core.hooksPath``,
``include.path`` and filter drivers all name commands that git executes, and a
read-write agent can write any of them into a repository in its workspace.
Running ``git status`` on the host against such a repository would hand that
agent code execution as the service user — which is why every git command here
runs inside a short-lived leaf: the role's image, ``--network=none``, the
workspace read-write, **no credential and no claude**.

The scripts themselves live in ``deploy/`` and are mounted read-only, so the
thing being executed is never inside the directory the agent can write.

**Honest limits.** A read-write agent can delete or rewrite
``refs/agentbridge/*`` in its own workspace. A checkpoint protects against a
mistake, not against a hostile agent, and rollback cannot undo anything that
happened outside the workspace.
"""

from __future__ import annotations

import asyncio
import json
import logging
import re

from . import config
from .roles import ROLES
from .tenant import Tenant

log = logging.getLogger("mcp-agentbridge")

CHECKPOINT_SCRIPT = "checkpoint.sh"
ROLLBACK_SCRIPT = "rollback.sh"

# Generous for a few git commands; a repository big enough to exceed this is
# one the whole design would struggle with.
LEAF_TIMEOUT = 60.0

# Task ids are generated by `broker.new_task_id` (12 hex chars). Validating
# the value here as well keeps a hand-published task message from putting
# anything else into a ref name or a file path.
TASK_ID_RE = re.compile(r"^[0-9a-f]{6,32}$")

# Repository paths come from the caller, so they are held to the same rules as
# workspace paths: one relative path segment sequence, no '..', no absolutes.
REPO_RE = re.compile(r"^[A-Za-z0-9._][A-Za-z0-9._/-]{0,127}$")


class CheckpointError(Exception):
    """A caller-fixable problem (reported, not raised)."""


def validate_task_id(task_id: str) -> str:
    if not TASK_ID_RE.match(task_id or ""):
        raise CheckpointError(
            f"invalid task id {task_id!r}: expected the id send_task returned"
        )
    return task_id


def validate_repo(repo: str | None) -> str:
    """``ALL``, or one repository path relative to the workspace."""
    if repo in (None, "", "ALL"):
        return "ALL"
    if not REPO_RE.match(repo) or ".." in repo.split("/"):
        raise CheckpointError(
            f"invalid repo {repo!r}: use a path relative to your workspace, "
            f"as fleet_status and the checkpoint report it"
        )
    return repo


def _script(name: str) -> str:
    path = config.AGENTBRIDGE_HOME / "deploy" / name
    if not path.is_file():
        raise CheckpointError(f"missing {name} at {path}")
    return str(path)


def _leaf(tenant: Tenant, role_name: str, script: str, args: list[str]) -> list[str]:
    """The podman argv for a git leaf. No credential, no claude, no network."""
    role = ROLES[role_name]
    return [
        "podman", "run", "--rm",
        "--cgroups=split",
        "--security-opt", "label=disable",
        "--security-opt", "no-new-privileges",
        "--network=none",
        "--tmpfs", "/tmp:rw,size=64m",
        "--log-driver=none",
        "-e", "HOME=/tmp",
        # Read-write: the point is to write refs. The script is mounted
        # read-only and from outside the workspace, so what executes is never
        # something the agent can edit.
        "-v", f"{tenant.workspace}:/workspace:rw",
        "-v", f"{script}:/script.sh:ro",
        "-w", "/workspace",
        role.image,
        "sh", "/script.sh", *args,
    ]


def checkpoint_command(tenant: Tenant, role_name: str) -> list[str]:
    """The command the bridge runs before each task, with {task_id} to fill in."""
    return _leaf(tenant, role_name, _script(CHECKPOINT_SCRIPT),
                 ["{task_id}", "/workspace"])


def rollback_command(tenant: Tenant, role_name: str, task_id: str,
                     repo: str, force: bool) -> list[str]:
    return _leaf(tenant, role_name, _script(ROLLBACK_SCRIPT),
                 [task_id, "/workspace", repo, "force" if force else "no"])


async def run_leaf(argv: list[str]) -> dict:
    """Run a git leaf and parse its JSON. Errors are reported, not raised."""
    try:
        proc = await asyncio.create_subprocess_exec(
            *argv, stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        out, err = await asyncio.wait_for(proc.communicate(), timeout=LEAF_TIMEOUT)
    except (TimeoutError, OSError) as exc:
        raise CheckpointError(f"the git leaf did not finish: {exc}") from None
    if proc.returncode != 0:
        detail = err.decode(errors="replace").strip()[-300:]
        raise CheckpointError(f"the git leaf failed (rc={proc.returncode}): {detail}")
    try:
        payload = json.loads(out.decode(errors="replace") or "{}")
    except json.JSONDecodeError:
        raise CheckpointError("the git leaf produced no JSON") from None
    if not isinstance(payload, dict):
        raise CheckpointError("the git leaf produced unexpected JSON")
    return payload


def role_for_worker(agent_id: str) -> str:
    """The role of a worker, from its id (`implementer-2` → `implementer`).

    Used to pick the image for a rollback leaf. Falls back to any read-write
    role, since a rollback needs to write refs whatever asked for it.
    """
    name = str(agent_id).rsplit("-", 1)[0]
    if name in ROLES:
        return name
    for candidate, role in ROLES.items():
        if role.workspace == "rw":
            return candidate
    raise CheckpointError("no read-write role is configured")
